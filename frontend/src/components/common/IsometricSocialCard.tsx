export const IsometricSocialCard: React.FC<IsometricSocialCardProps> = ({
  orientation = 'vertical',
  compact = false,
  className = '',
  customItems,
  showTitle = false,
}) => {
  const { profile } = useDeveloperStore();

  const connectedSocialLinks: SocialLink[] =
    profile?.social_links && profile.social_links.length > 0
      ? profile.social_links
      : [
          {
            platform: 'github',
            name: 'GitHub',
            url: `https://github.com/${profile?.username || 'shrutirai29'}`,
          },
          ...(profile?.username?.toLowerCase() === 'shrutirai29'
            ? ([
                {
                  platform: 'linkedin',
                  name: 'LinkedIn',
                  url: 'https://www.linkedin.com/in/shruti-rai-3b5055304',
                },
                {
                  platform: 'instagram',
                  name: 'Instagram',
                  url: 'https://www.instagram.com/shruti.r8524/',
                },
              ] as SocialLink[])
            : []),
        ];

  const mappedItems: SocialItem[] = connectedSocialLinks.map((link, idx) => {
    const iconMeta = PLATFORM_ICONS[link.platform] || PLATFORM_ICONS.website;
    return {
      id: `${link.platform}-${idx}`,
      name: link.name,
      url: link.url,
      viewBox: iconMeta.viewBox,
      svgPath: iconMeta.svgPath,
      brandClass: iconMeta.brandClass,
    };
  });

  const items = customItems || mappedItems;

  return (
    <div
      className={`card iso-card ${orientation === 'horizontal' ? 'horizontal' : ''} ${
        compact ? 'compact' : ''
      } ${className}`}
    >
      {showTitle && (
        <div className="pt-3 px-4 text-center font-mono text-[10px] uppercase tracking-wider font-semibold text-[#64748B] dark:text-[#94A3B8]">
          GitHub Connected Links
        </div>
      )}
      <ul>
        {items.map((item) => (
          <li
            key={item.id}
            className={`iso-pro ${item.brandClass || ''} ${compact ? 'iso-compact' : ''}`}
            title={`Open ${item.name} (${item.url})`}
          >
            <span />
            <span />
            <span />
            <a
              href={item.url}
              target="_blank"
              rel="noreferrer"
              aria-label={item.name}
            >
              <svg
                viewBox={item.viewBox}
                xmlns="http://www.w3.org/2000/svg"
                className="svg"
              >
                <path d={item.svgPath} />
              </svg>
            </a>
            <div className="text">{item.name}</div>
          </li>
        ))}
      </ul>
    </div>
  );
};
